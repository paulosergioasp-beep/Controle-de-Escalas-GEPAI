// Gera rótulos de meses retroativos a partir de uma data de referência recente
// 120 meses: Mês -119 até Mês 0
export function getMonthLabels(totalMonths = 120) {
  const labels = [];
  const now = new Date(2024, 8, 1); // Setembro/2024 como base consolidada
  for (let i = totalMonths - 1; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    const monthShort = d.toLocaleString('pt-BR', { month: 'short' });
    const yearShort = d.getFullYear().toString().slice(-2);
    labels.push(`${monthShort}/${yearShort}`);
  }
  return labels;
}

